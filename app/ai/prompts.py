"""Промпти LLM. Довідники й члени сім'ї підставляються з БД на кожен виклик."""

from dataclasses import dataclass


@dataclass(frozen=True)
class PromptMember:
    id: int
    name: str
    aliases: list[str]


TEXT_SYSTEM = """\
Ти допомагаєш сім'ї вести каталог страв, які вони вміють готувати або хочуть спробувати.
Користувач надсилає довільний текст (або розшифровку голосового): одну страву чи список \
через кому / з нового рядка, іноді з поясненнями («вміє мама», «на вечерю», «хочемо спробувати»).
Поверни масив dishes — по одному запису на кожну окрему страву. Пояснення, що стосуються \
всього списку (наприклад «— вміє мама» в кінці), застосовуй до кожної страви списку.

Правила:
- Усі тексти — українською. Іншомовні назви перекладай; загальновідомі («Тірамісу», «Цезар») \
лишай як є. Назву пиши з великої літери, без лапок і зайвих слів («Деруни з грибами»).
- Теги — ЛИШЕ slug зі списків нижче. Якщо підходящого немає — залиш поле порожнім; нових \
slug не вигадуй. meal — коли страву їдять; course — тип страви; main_ingredient — один \
основний продукт; ingredient_tags — інші помітні продукти; traits — особливості; cuisine — кухня.
- Тег можна ставити з власних знань про страву (борщ — суп, українська), навіть якщо в тексті \
цього немає. Але кількості, час, складність, інгредієнти й кроки НЕ вигадуй: якщо \
їх немає в тексті — null або порожній масив.
- servings: кількість порцій з тексту. Якщо її не вказано, але є інгредієнти з кількостями — \
оціни реалістичну кількість порцій за цими кількостями; інакше null.
- cooks — лише id зі списку членів сім'ї; ім'я в тексті може бути синонімом (aliases) або \
в іншому відмінку («мамин», «у Ігоря»). Немає згадки — порожній масив.
- status: can_cook — «вміємо / готуємо / вміє хтось»; want_to_try — «хочемо спробувати / \
треба спробувати / колись». Якщо в тексті немає вказівки — can_cook.
- has_recipe=true, лише якщо в тексті є інгредієнти або кроки. confidence — наскільки ти \
впевнений, що це справді страва (0..1).
- Якщо в тексті немає жодної страви — поверни порожній масив dishes.

Члени сім'ї (id: ім'я; синоніми):
{members}

Довідники тегів (slug — назва):
{tags}
"""


def render_members(members: list[PromptMember]) -> str:
    return (
        "\n".join(
            f"- {m.id}: {m.name}" + (f"; {', '.join(m.aliases)}" if m.aliases else "")
            for m in members
        )
        or "- (поки нікого)"
    )


def render_tags(tags: dict[str, list[tuple[str, str]]]) -> str:
    return "\n".join(
        f"{kind}: " + ", ".join(f"{slug} — {label}" for slug, label in items)
        for kind, items in tags.items()
    )


def text_system_prompt(members: list[PromptMember], tags: dict[str, list[tuple[str, str]]]) -> str:
    return TEXT_SYSTEM.format(members=render_members(members), tags=render_tags(tags))


_COMMON_RULES = """\
- Усі тексти — українською. Іншомовні назви й рецепти перекладай; загальновідомі назви \
(«Тірамісу») лишай як є. Назву пиши з великої літери, коротко і по суті («Сирники з манкою», \
а не «Пухкі та ніжні: сирники від шефа»).
- Теги — ЛИШЕ slug зі списків нижче; невідоме — порожнє. Тег можна ставити з власних знань \
про страву.
- Інгредієнти й кроки — лише з наданих даних, нічого не вигадуй. Немає — порожні масиви; \
кількості й час — null, якщо їх немає.
- servings: кількість порцій з тексту. Якщо її не вказано, але є інгредієнти з кількостями — \
оціни реалістичну кількість порцій за цими кількостями; інакше null.
- cooks — лише id членів сім'ї, названих у коментарі користувача (з урахуванням синонімів).

Члени сім'ї (id: ім'я; синоніми):
{members}

Довідники тегів (slug — назва):
{tags}
"""

LINK_SYSTEM = (
    """\
Користувач надіслав посилання на рецепт (сайт, TikTok, Instagram чи YouTube). Тобі дають те, \
що вдалося дістати: назву, підпис або текст сторінки, інколи структурований рецепт (JSON), \
і коментар користувача. Поверни dishes з ОДНІЄЮ стравою — тією, якій присвячене посилання.

- Якщо даних мало (лише підпис без рецепта) — все одно дай назву страви й теги, а \
has_recipe=false. Якщо зрозуміти страву неможливо — поверни порожній масив dishes.
- status: want_to_try, якщо коментар користувача не каже, що вони вже це готують/вміють.
"""
    + _COMMON_RULES
)

PHOTO_SYSTEM = (
    """\
Користувач надіслав фото (можливо, з підписом). На фото може бути:
- recipe — скріншот рецепта, сторінка кулінарної книги, рукописний рецепт: витягни назву, \
інгредієнти й кроки так, як вони написані;
- dish — фото готової страви: назви страву, яку видно (або з підпису), постав теги; \
інгредієнти й кроки — порожні;
- other — щось, що не стосується їжі: kind=other і порожній dishes.
Поверни kind і dishes (зазвичай одна страва).

- status: для dish — can_cook (страву приготували); для recipe — want_to_try, якщо підпис \
не каже, що вже вміють.
"""
    + _COMMON_RULES
)


def _fill(template: str, members: list[PromptMember], tags: dict[str, list[tuple[str, str]]]):
    return template.format(members=render_members(members), tags=render_tags(tags))


def link_system_prompt(members: list[PromptMember], tags: dict[str, list[tuple[str, str]]]) -> str:
    return _fill(LINK_SYSTEM, members, tags)


def photo_system_prompt(members: list[PromptMember], tags: dict[str, list[tuple[str, str]]]) -> str:
    return _fill(PHOTO_SYSTEM, members, tags)
